test('MCP tasks submit, report actual output and verification, paginate events, and cancel', {skip: !harness && 'set LEIO_HARNESS_BIN to the built harness'}, async t => {
  const repo=mkdtempSync(path.join(tmpdir(),'leio-task-mcp-'));
  writeFileSync(path.join(repo,'.gitignore'),'.leio-code/\n');
  writeFileSync(path.join(repo,'code.txt'),'before\n');
  for(const args of [['init','-q'],['add','.'],['-c','user.name=Task Test','-c','user.email=test@example.invalid','commit','-qm','baseline']])execFileSync('git',args,{cwd:repo});
  const transport=new StdioClientTransport({command:process.execPath,args:[path.join(here,'index.js')],env:{...process.env,LEIO_HARNESS_BIN:harness,LEIO_CODE_REPO_ROOT:repo},stderr:'pipe'});
  const client=new Client({name:'harness-tasks-test',version:'1.0'});await client.connect(transport);
  t.after(()=>client.close());
  const call=async(action,fields={})=>{
    const result=await client.callTool({name:'leio_code_task',arguments:{action,repo_root:repo,...fields}});
    assert.ok(!result.isError,JSON.stringify(result));return result.structuredContent.task;
  };
  assert.deepEqual((await call('list')).runs,[]);
  const nested=path.join(repo,'module');mkdirSync(nested);
  const nestedAttempt=await client.callTool({name:'leio_code_task',arguments:{action:'submit',repo_root:nested,task:'must not execute from a Git subdirectory',worker:'fixture',argv:['/usr/bin/true'],verify_argv:['/usr/bin/true']}});
  assert.equal(nestedAttempt.isError,true);assert.match(nestedAttempt.content[0].text,/Git checkout root/);
  assert.equal(existsSync(path.join(nested,'.leio-code')),false);

  const submitted=await call('submit',{task:'change the fixture; do not commit',worker:'fixture',argv:['sh','-c','echo actual-output; sleep .3; echo after > code.txt'],verify_argv:['sh','-c','test "$(cat code.txt)" = after'],timeout_ms:3000});
  const id=submitted.runId;
  let result;
  const deadline=Date.now()+10000;
  do {result=await call('result',{run_id:id});if(['failed','succeeded'].includes(result.state))break;await new Promise(resolve=>setTimeout(resolve,30));}while(Date.now()<deadline);
  assert.equal(result.state,'succeeded');assert.equal(result.verificationResult.status,'passed');assert.ok(result.diffPath);assert.equal(result.supervisorAlive,false);
  const events=await call('events',{run_id:id,limit:2});assert.equal(events.events.length,2);assert.equal(events.hasMore,true);
  const continued=await call('events',{run_id:id,after:events.nextAfter});assert.ok(continued.events.some(e=>e.kind==='output'));
  execFileSync('git',['restore','code.txt'],{cwd:repo});
  const slow=await call('submit',{task:'cancel fixture',worker:'fixture',argv:['sleep','30'],verify_argv:['true'],timeout_ms:60000});
  await call('cancel',{run_id:slow.runId});
  do {result=await call('status',{run_id:slow.runId});if(result.state==='cancelled')break;await new Promise(resolve=>setTimeout(resolve,30));}while(Date.now()<deadline);
  assert.equal(result.state,'cancelled');
  const invalid=await client.callTool({name:'leio_code_task',arguments:{action:'submit',repo_root:repo,task:'missing argv'}});
  assert.equal(invalid.isError,true);
});

test('MCP review snapshots current edits without manual preparation, returns provenance and is discoverable from source', {skip: !harness && 'set LEIO_HARNESS_BIN to the built harness'}, async t=>{
  const {readFileSync,rmSync,realpathSync}=await import('node:fs');
  const repo=realpathSync(mkdtempSync(path.join(tmpdir(),'leio-review-mcp-')));
  writeFileSync(path.join(repo,'.gitignore'),'.leio-code/\n');writeFileSync(path.join(repo,'code.txt'),'baseline\n');
  for(const args of [['init','-q'],['add','.'],['-c','user.name=Review Test','-c','user.email=test@example.invalid','commit','-qm','baseline']])execFileSync('git',args,{cwd:repo});
  const head=execFileSync('git',['rev-parse','HEAD'],{cwd:repo,encoding:'utf8'});
  writeFileSync(path.join(repo,'code.txt'),'current dirty content\n');writeFileSync(path.join(repo,'new.txt'),'new source file\n');
  const binary=path.join(repo,'mock codex');
  writeFileSync(binary,`#!${process.execPath}\nconst fs=require('node:fs'),args=process.argv.slice(2);\nif(args.includes('mcp')){console.log(JSON.stringify([{name:'external-tools',enabled:!args.includes('mcp_servers.external-tools.enabled=false')}]));process.exit(0);}\nif(args[args.indexOf('--sandbox')+1]!=='read-only'||!args.includes('mcp_servers.external-tools.enabled=false')||args.includes('--ignore-user-config'))process.exit(7);\nif(fs.readFileSync('code.txt','utf8')!=='current dirty content\\n'||fs.readFileSync('new.txt','utf8')!=='new source file\\n')process.exit(8);\nconsole.log(JSON.stringify({type:'item.completed',item:{type:'agent_message',text:'Reviewed current dirty content; no concrete findings'}}));\n`,{mode:0o755});
  const client=new Client({name:'captured-review-test',version:'1.0'});
  await client.connect(new StdioClientTransport({command:process.execPath,args:[path.join(here,'index.js')],env:{...process.env,LEIO_HARNESS_BIN:harness,LEIO_DISABLE_EVENTS:'1'},stderr:'pipe'}));
  t.after(async()=>{await client.close();rmSync(repo,{recursive:true,force:true});});
  const call=async fields=>client.callTool({name:'leio_code_task',arguments:{repo_root:repo,...fields}});
  const submitted=await call({action:'review',sources:['code.txt','new.txt'],task:'Review these current files',codex_binary:binary,timeout_ms:5000});
  assert.ok(!submitted.isError,JSON.stringify(submitted));
  const data=submitted.structuredContent,snapshot=data.repo_root,id=data.task.runId;
  assert.notEqual(snapshot,repo);assert.equal(data.review_source.source_repo,repo);
  assert.equal(data.review_source.files.length,2);assert.equal(data.next_calls[0].arguments.repo_root,snapshot);
  let result;const deadline=Date.now()+10000;
  do {result=await call({action:'result',repo_root:snapshot,run_id:id});if(['failed','succeeded'].includes(result.structuredContent.task.state))break;await new Promise(resolve=>setTimeout(resolve,30));}while(Date.now()<deadline);
  assert.ok(!result.isError,JSON.stringify(result));
  assert.equal(result.structuredContent.task.state,'succeeded');
  assert.equal(result.structuredContent.review.next_action,'review_findings');
  assert.match(result.structuredContent.review.assurance,/snapshot integrity only/);
  assert.deepEqual(result.structuredContent.review.changed_files,[]);
  assert.match(result.structuredContent.review.artifacts.worker_stdout.text,/no concrete findings/);
  assert.match(result.structuredContent.review.artifacts.verification_stdout.text,/selected_files_unchanged/);
  assert.equal(result.structuredContent.review_source.source_repo,repo);
  const listed=await call({action:'list'});assert.equal(listed.structuredContent.review_runs.length,1);
  assert.equal(listed.structuredContent.review_runs[0].run_id,id);
  assert.equal(listed.structuredContent.review_runs[0].next_call.arguments.repo_root,snapshot);
  assert.equal(readFileSync(path.join(repo,'code.txt'),'utf8'),'current dirty content\n');
  assert.equal(execFileSync('git',['rev-parse','HEAD'],{cwd:repo,encoding:'utf8'}),head);
  const refusing=path.join(repo,'ignores isolation overrides');
  const escaped=path.join(repo,'SHOULD_NOT_RUN');
  writeFileSync(refusing,`#!${process.execPath}\nconst fs=require('node:fs');\nif(process.argv.includes('mcp'))console.log(JSON.stringify([{name:'external-tools',enabled:true}]));else fs.writeFileSync(${JSON.stringify(escaped)},'unexpected worker');\n`,{mode:0o755});
  const unsafe=await call({action:'review',sources:['code.txt'],codex_binary:refusing});
  assert.equal(unsafe.isError,true);assert.match(unsafe.content[0].text,/servers are still enabled/);
  assert.equal(existsSync(escaped),false);
  const afterRefusal=await call({action:'list'});assert.equal(afterRefusal.structuredContent.review_runs.length,1);
});

test('Review receipt failure preserves the started run, discovery, events and cancellation with unavailable provenance', {skip: !harness && 'set LEIO_HARNESS_BIN to the built harness'}, async t=>{
  const fs=await import('node:fs');
  const repo=fs.realpathSync(mkdtempSync(path.join(tmpdir(),'leio-review-recovery-')));
  writeFileSync(path.join(repo,'code.txt'),'source stays unchanged\n');
  for(const args of [['init','-q'],['add','.'],['-c','user.name=Recovery Test','-c','user.email=test@example.invalid','commit','-qm','baseline']])execFileSync('git',args,{cwd:repo});
  const binary=path.join(repo,'blocks catalog receipt');
  writeFileSync(binary,`#!${process.execPath}\nconst fs=require('node:fs'),path=require('node:path');\nif(process.argv.includes('mcp')){fs.mkdirSync(path.join(path.dirname(process.cwd()),'record.json'),{recursive:true});console.log('[]');}else{console.log('review worker ready');setInterval(()=>{},1000);}\n`,{mode:0o755});
  const client=new Client({name:'review-recovery-test',version:'1.0'});
  await client.connect(new StdioClientTransport({command:process.execPath,args:[path.join(here,'index.js')],env:{...process.env,LEIO_HARNESS_BIN:harness,LEIO_DISABLE_EVENTS:'1'},stderr:'pipe'}));
  const catalog=path.join(repo,'.leio-code/harness/reviews');
  t.after(async()=>{
    // Clean up every owned run even when an assertion fails after submission.
    if(fs.existsSync(catalog))for(const entry of fs.readdirSync(catalog)){
      const root=path.join(catalog,entry,'snapshot'),runs=path.join(root,'.leio-code/harness/runs');
      if(!fs.existsSync(runs))continue;
      for(const id of fs.readdirSync(runs)){
        execFileSync(harness,['task','cancel','--repo',root,'--run-id',id]);
        const until=Date.now()+10000;
        while(Date.now()<until){const status=JSON.parse(execFileSync(harness,['task','status','--repo',root,'--run-id',id],{encoding:'utf8'}));if(!status.supervisorAlive)break;await new Promise(r=>setTimeout(r,30));}
      }
    }
    await client.close();fs.rmSync(repo,{recursive:true,force:true});
  });
  const call=async fields=>client.callTool({name:'leio_code_task',arguments:{repo_root:repo,...fields}});
  const submitted=await call({action:'review',sources:['code.txt'],codex_binary:binary,timeout_ms:60000});
  assert.ok(!submitted.isError,JSON.stringify(submitted));
  const data=submitted.structuredContent,args={repo_root:data.repo_root,run_id:data.task.runId};
  assert.ok(data.review_warnings.some(w=>w.kind==='review_catalog_record_failed'));
  assert.ok(data.next_calls.some(c=>c.arguments.action==='cancel' && c.arguments.run_id===args.run_id));
  const listing=await call({action:'list'});assert.ok(!listing.isError,JSON.stringify(listing));
  assert.equal(listing.structuredContent.review_runs.length,1);
  assert.equal(listing.structuredContent.review_runs[0].run_id,args.run_id);
  assert.equal(listing.structuredContent.review_runs[0].recovered,true);
  assert.equal(listing.structuredContent.review_catalog_incomplete,true);
  writeFileSync(path.join(args.repo_root,'.leio-code/review-source.json'),'{corrupt');
  const status=await call({action:'status',...args});assert.ok(!status.isError,JSON.stringify(status));
  assert.equal(status.structuredContent.task.runId,args.run_id);
  assert.ok(status.structuredContent.review_warnings.some(w=>w.kind==='review_source_unavailable'));
  const events=await call({action:'events',...args});assert.ok(!events.isError,JSON.stringify(events));
  assert.ok(events.structuredContent.task.events.length);
  const cancelled=await call({action:'cancel',...args});assert.ok(!cancelled.isError,JSON.stringify(cancelled));
  let result;const deadline=Date.now()+10000;
  do {result=await call({action:'result',...args});assert.ok(!result.isError,JSON.stringify(result));if(result.structuredContent.task.state==='cancelled')break;await new Promise(r=>setTimeout(r,30));}while(Date.now()<deadline);
  assert.equal(result.structuredContent.task.state,'cancelled');assert.equal(result.structuredContent.task.supervisorAlive,false);
  assert.equal(fs.readFileSync(path.join(repo,'code.txt'),'utf8'),'source stays unchanged\n');
});

