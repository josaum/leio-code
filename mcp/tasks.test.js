  t.after(async()=>{await client.close();execFileSync('git',['worktree','remove','--force',worktree],{cwd:source});rmSync(parent,{recursive:true,force:true});});
  assert.match(client.getInstructions(),/leio_code_task/);
  const catalog=await client.listTools();
