  const {mkdirSync,readFileSync,rmSync,realpathSync}=await import('node:fs');
  const source=path.join(parent,'source repo'),worktree=path.join(parent,'clean worktree');mkdirSync(source);
  writeFileSync(path.join(source,'.gitignore'),'.leio-code/\n');
  writeFileSync(path.join(source,'code.txt'),'before\n');
  for(const args of [['init','-q'],['add','.'],['-c','user.name=Task Test','-c','user.email=test@example.invalid','commit','-qm','baseline']])execFileSync('git',args,{cwd:source});
  writeFileSync(path.join(source,'code.txt'),'local edit stays here\n');
  const binary=path.join(parent,'mock codex');
  writeFileSync(binary,`#!${process.execPath}\nconst fs=require('node:fs');\nfs.writeFileSync('handoff.json',JSON.stringify(process.argv.slice(2)));\nfs.writeFileSync('code.txt','after\\n');\nconsole.log(JSON.stringify({type:'item.completed',item:{type:'agent_message',text:'Changed code.txt only; review the patch'}}));\n`,{mode:0o755});
  const transport=new StdioClientTransport({command:process.execPath,args:[path.join(here,'index.js')],env:{...process.env,LEIO_HARNESS_BIN:harness,LEIO_DISABLE_EVENTS:'1'},stderr:'pipe'});
